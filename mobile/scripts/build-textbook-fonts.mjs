// Builds src/components/textbook/fonts.generated.ts: KaTeX's stylesheet and the textbook fonts
// (Source Serif 4 for text, Inter for headings), with every font file inlined as a data: URL.
//
// The textbook reader runs in a web view on Android (an Expo DOM component), where font files
// from node_modules can't be loaded by URL in every build, and the app also updates over the
// air. Inlining makes the reader self-contained: it looks the same on web, Android and offline.
//
// Runs on `npm install` (postinstall). The output is not committed (see .gitignore).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'src/components/textbook/fonts.generated.ts');

const woff2 = (file) => `url(data:font/woff2;base64,${readFileSync(file).toString('base64')}) format('woff2')`;

// KaTeX: keep only the woff2 source of each @font-face (every browser in use reads woff2).
const katexDir = dirname(require.resolve('katex/dist/katex.min.css'));
const katexCss = readFileSync(join(katexDir, 'katex.min.css'), 'utf8').replace(
  /src:url\(fonts\/([^)]+?)\.woff2\) format\("woff2"\)(?:,url\([^)]*\) format\("[^"]*"\))*/g,
  (_, name) => `src:${woff2(join(katexDir, 'fonts', `${name}.woff2`))}`,
);
if (/url\(fonts\//.test(katexCss)) throw new Error('KaTeX CSS still links font files: its format changed.');

const fontFile = (pkg, file) => join(dirname(require.resolve(`${pkg}/package.json`)), 'files', file);
const face = (family, file, style) =>
  `@font-face{font-family:'${family}';font-style:${style};font-display:swap;font-weight:100 900;src:${woff2(file)}}`;
const textCss = [
  face('StudyMe Serif', fontFile('@fontsource-variable/source-serif-4', 'source-serif-4-latin-wght-normal.woff2'), 'normal'),
  face('StudyMe Serif', fontFile('@fontsource-variable/source-serif-4', 'source-serif-4-latin-wght-italic.woff2'), 'italic'),
  face('StudyMe Sans', fontFile('@fontsource-variable/inter', 'inter-latin-wght-normal.woff2'), 'normal'),
].join('\n');

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/build-textbook-fonts.mjs. Do not edit.\n` +
    `export const KATEX_CSS = ${JSON.stringify(katexCss)};\n` +
    `export const TEXT_FONTS_CSS = ${JSON.stringify(textCss)};\n`,
);
console.log(`textbook fonts: ${Math.round((katexCss.length + textCss.length) / 1024)} KB -> ${out}`);
